def lit(v):
    if v is None: return "NULL"
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"
def insert(table, cols, rows):
    return [f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(lit(x) for x in r)});" for r in rows]

